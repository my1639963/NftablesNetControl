/* Assemble a standalone ucode program from the real backend source: the pure
 * event-engine functions plus tools/engine-harness.driver.uc. Upload the output
 * to the router and run it with `ucode` - it touches neither UCI nor nftables.
 *
 *   ELECTRON_RUN_AS_NODE=1 node tools/engine-harness.cjs > tmp/nc-engine.uc
 *
 * HARNESS_SRC points the extractor at another copy of the backend. Two builds of
 * this file - one from the old source, one from the new - produce two programs
 * whose outputs must match byte for byte, which is how a refactor that promises
 * to change no behaviour gets proved instead of argued.
 *
 *   HARNESS_SRC=tmp/h134/pre-luci.netcontrol node tools/engine-harness.cjs > tmp/pre.uc
 *
 * HARNESS_DRIVER swaps in another driver, which is how an assertion here gets
 * checked rather than trusted: build with a deliberately broken copy and the
 * count it guards has to move.
 */
const fs = require('fs');
const path = require('path');

const SRC = process.env.HARNESS_SRC || path.join(__dirname, '..', 'src', 'luci-app-netcontrol', 'root',
	'usr', 'share', 'rpcd', 'ucode', 'luci.netcontrol');
const DRIVER = process.env.HARNESS_DRIVER || path.join(__dirname, 'engine-harness.driver.uc');
const lines = fs.readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n').split('\n');

/* Dependency order: a function is extracted before its callers, because ucode
 * looks names up where it stands. */
const NEEDED = [
	'is_set', 'strjoin', 'merge', 'to_int', 'shellquote', 'run', 'is_bool', 'norm_mac',
	'tz_prefix', 'local_parts', 'iso_at', 'hhmm_total', 'contains_value',
	'cycle_matches', 'rule_target', 'flip', 'hhmm', 'event_stamp', 'rule_window',
	'rule_moments', 'rule_stamps', 'local_midnight', 'day_range', 'bucket_of',
	'push_bucket', 'push_day_events', 'events_in_range', 'rule_next_event'
];

/* A name a build of the backend may not have yet. The driver only reaches these
 * through functions it also skips, so the two builds still print comparable text. */
const OPTIONAL = new Set(['rule_moments', 'push_day_events']);

function extract(name) {
	const start = lines.findIndex((l, i) => i > 30 && l.startsWith(`function ${name}(`));

	if (start < 0) {
		if (OPTIONAL.has(name))
			return null;

		throw new Error(`function ${name} not found`);
	}

	for (let i = start + 1; i < lines.length; i++)
		if (lines[i].startsWith('}'))
			return lines.slice(start, i + 1).join('\n');

	throw new Error(`unterminated ${name}`);
}

const out = [
	'#!/usr/bin/ucode',
	`/* GENERATED by tools/engine-harness.cjs from ${path.basename(SRC)} - do not edit */`,
	"import { access, popen } from 'fs';",
	NEEDED.map(extract).filter((f) => f !== null).join('\n\n'),
	fs.readFileSync(DRIVER, 'utf8').replace(/\r\n/g, '\n').trim()
].join('\n\n');

process.stdout.write(out);
