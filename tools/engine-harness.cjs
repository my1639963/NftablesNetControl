/* Assemble a standalone ucode program from the real backend source: the pure
 * event-engine functions plus tools/engine-harness.driver.uc. Upload the output
 * to the router and run it with `ucode` - it touches neither UCI nor nftables.
 *
 *   ELECTRON_RUN_AS_NODE=1 node tools/engine-harness.cjs > tmp/nc-engine.uc
 */
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src', 'luci-app-netcontrol', 'root',
	'usr', 'share', 'rpcd', 'ucode', 'luci.netcontrol');
const DRIVER = path.join(__dirname, 'engine-harness.driver.uc');
const lines = fs.readFileSync(SRC, 'utf8').replace(/\r\n/g, '\n').split('\n');

const NEEDED = [
	'is_set', 'strjoin', 'merge', 'to_int', 'shellquote', 'run', 'is_bool', 'norm_mac',
	'tz_prefix', 'local_parts', 'iso_at', 'hhmm_total', 'contains_value',
	'cycle_matches', 'rule_target', 'flip', 'rule_window', 'local_midnight',
	'day_range', 'bucket_of', 'push_bucket', 'events_in_range', 'rule_next_event'
];

function extract(name) {
	const start = lines.findIndex((l, i) => i > 30 && l.startsWith(`function ${name}(`));

	if (start < 0)
		throw new Error(`function ${name} not found`);

	for (let i = start + 1; i < lines.length; i++)
		if (lines[i].startsWith('}'))
			return lines.slice(start, i + 1).join('\n');

	throw new Error(`unterminated ${name}`);
}

const out = [
	'#!/usr/bin/ucode',
	'/* GENERATED by tools/engine-harness.cjs from luci.netcontrol - do not edit */',
	"import { access, popen } from 'fs';",
	NEEDED.map(extract).join('\n\n'),
	fs.readFileSync(DRIVER, 'utf8').replace(/\r\n/g, '\n').trim()
].join('\n\n');

process.stdout.write(out);
